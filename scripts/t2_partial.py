#!/usr/bin/env python3
"""Generate results/T2-PARTIAL.md from the stored T2 evaluation receipts.

This is an *exploratory* reader, not the registered five-arm verdict. It loads
`results/eval/t2-<arm>.json` for the arms that exist, recomputes the per-task
outcomes and the primary composite PC from per-item rows, and writes a paired
X-vs-H comparison with a percentile paired bootstrap. Nothing here changes a
threshold or reads `docs/capability-preregistration.json`.

The registered decision is produced separately by `oracle/eval/t2_decision.py`
once all five arms (including H*) exist. This document says so explicitly and
must not be cited as the verdict.

Output numbers are generated, never hand-written:
  python3 scripts/t2_partial.py --out results/T2-PARTIAL.md
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "oracle", "eval"))
sys.path.insert(0, os.path.join(ROOT, "oracle", "train"))

import numpy as np  # noqa: E402

from metrics import paired_bootstrap  # noqa: E402
from t2_decision import (  # noqa: E402
    ArmMetrics, TASKS, composite_bootstrap, composite_paired,
)

SEED = 20261115
RESAMPLES = 10_000
PAIR = ("X", "H")
CONTEXT = ("D0", "M", "D")


def sha256(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_arm(arm: str) -> tuple[ArmMetrics, str]:
    path = os.path.join(ROOT, "results", "eval", f"t2-{arm}.json")
    with open(path, "r", encoding="utf-8") as handle:
        receipt = json.load(handle)
    return ArmMetrics(arm, receipt), path


def fmt(value, digits: int = 4) -> str:
    if value is None:
        return "—"
    return f"{value:.{digits}f}"


def ci(block: dict) -> str:
    return f"[{fmt(block['ci_low'])}, {fmt(block['ci_high'])}]"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=os.path.join(ROOT, "results", "T2-PARTIAL.md"))
    args = ap.parse_args(argv)

    left, left_path = load_arm(PAIR[0])
    right, right_path = load_arm(PAIR[1])
    context = {}
    for arm in CONTEXT:
        path = os.path.join(ROOT, "results", "eval", f"t2-{arm}.json")
        if os.path.isfile(path):
            context[arm] = load_arm(arm)[0]

    # Item identity must agree or the pairing is not paired.
    for task in TASKS:
        if left.task_items[task] != right.task_items[task]:
            raise SystemExit(f"item ids differ between {PAIR[0]} and {PAIR[1]} on {task}")
        if left.task_values[task].size != right.task_values[task].size:
            raise SystemExit(f"item counts differ on {task}")

    table = {}
    for task in TASKS:
        a = left.task_values[task]  # X
        b = right.task_values[task]  # H
        both = int(np.sum((a == 1) & (b == 1)))
        only_x = int(np.sum((a == 1) & (b == 0)))
        only_h = int(np.sum((a == 0) & (b == 1)))
        neither = int(np.sum((a == 0) & (b == 0)))
        table[task] = {
            "n": int(a.size),
            "x": float(a.mean()),
            "h": float(b.mean()),
            "both": both,
            "only_x": only_x,
            "only_h": only_h,
            "neither": neither,
            "paired": paired_bootstrap(b, a, seed=SEED, resamples=RESAMPLES),
        }

    pc_x = composite_bootstrap(left.task_values, SEED, RESAMPLES)
    pc_h = composite_bootstrap(right.task_values, SEED, RESAMPLES)
    pc_paired = composite_paired(right.task_values, left.task_values, SEED, RESAMPLES)

    # Recomputed PC must match the receipt's own stored per-task means; a
    # mismatch means the reader and the harness disagree and the partial record
    # would be reporting a different statistic than the registered one.
    stored = {}
    for arm in (PAIR[0], PAIR[1]):
        path = os.path.join(ROOT, "results", "eval", f"t2-{arm}.json")
        summary = json.load(open(os.path.join(ROOT, "results", "t2", arm, "eval.json")))
        stored[arm] = {
            "path": path,
            "sha256": sha256(path),
            "summary_sha256": sha256(os.path.join(ROOT, "results", "t2", arm, "eval.json")),
            "stored_per_task": summary.get("per_task"),
            "stored_pc": summary.get("primary_composite_pc"),
        }

    lines = []
    lines.append("# T2 partial record — exploratory X vs H comparison")
    lines.append("")
    lines.append(f"Generated by `scripts/t2_partial.py` at "
                 f"{datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')} from the stored "
                 "evaluation receipts. **This is not the registered five-arm verdict.**")
    lines.append("")
    lines.append("## Status and scope")
    lines.append("")
    lines.append("- `H*` has not reported at the time of writing; the fresh capability run and "
                 "the registered five-arm decision (`oracle/eval/t2_decision.py`) are outstanding.")
    lines.append(f"- This record compares **{PAIR[0]} vs {PAIR[1]} only**, from the existing "
                 "`results/eval/t2-*.json` per-item rows. It is exploratory evidence, not a "
                 "substitute for the registered verdict, and it may not be cited as one.")
    lines.append("- The historical `X` and `H` dispatch semantics are `legacy`, certified by "
                 "`results/t2/PROVENANCE-AMENDMENT-X-and-H.json`; the corrected-dispatch "
                 "sensitivity re-evaluation is registered and has not been run.")
    lines.append("")
    lines.append("## Inputs")
    lines.append("")
    lines.append("| arm | raw per-item receipt | sha256 | summary receipt | sha256 |")
    lines.append("| --- | --- | --- | --- | --- |")
    for arm in PAIR:
        lines.append(f"| {arm} | `results/eval/t2-{arm}.json` | "
                     f"`{stored[arm]['sha256'][:16]}…` | `results/t2/{arm}/eval.json` | "
                     f"`{stored[arm]['summary_sha256'][:16]}…` |")
    lines.append("")
    lines.append("## Method")
    lines.append("")
    lines.append(f"- Outcomes are read from per-item rows: HumanEval `passed`, GSM8K `correct`, "
                 f"TruthfulQA `correct`. Items are paired by id and the id lists must be "
                 f"identical, which they are.")
    lines.append(f"- PC is the equal-weight mean of the three task accuracies, the registered "
                 f"endpoint (`docs/EXPERIMENT-CONTRACT.md` T2.9). Per-task and composite "
                 f"intervals are percentile paired bootstraps over items, seed {SEED}, "
                 f"{RESAMPLES} resamples. Differences below are **H − X** (positive means H "
                 f"is higher).")
    lines.append(f"- Reusing the repo primitives `metrics.paired_bootstrap`, "
                 f"`t2_decision.composite_bootstrap` and `t2_decision.composite_paired` keeps "
                 f"the statistic identical to the registered reader.")
    lines.append("")
    lines.append("## Per-task outcomes")
    lines.append("")
    lines.append("| task | n | X | H | H − X | 95% paired CI | both | X only | H only | neither |")
    lines.append("| --- | ---: | ---: | ---: | ---: | --- | ---: | ---: | ---: | ---: |")
    for task in TASKS:
        row = table[task]
        p = row["paired"]
        lines.append(f"| {task} | {row['n']} | {fmt(row['x'])} | {fmt(row['h'])} | "
                     f"{fmt(p['mean_difference'])} | {ci(p)} | {row['both']} | "
                     f"{row['only_x']} | {row['only_h']} | {row['neither']} |")
    lines.append("")
    lines.append("## Per-arm composite (PC)")
    lines.append("")
    lines.append("| arm | PC | 95% bootstrap CI | HumanEval | GSM8K | TruthfulQA |")
    lines.append("| --- | ---: | --- | ---: | ---: | ---: |")
    for name, arm in [(PAIR[0], left), (PAIR[1], right)] + list(context.items()):
        block = composite_bootstrap(arm.task_values, SEED, RESAMPLES)
        tm = block["task_means"]
        lines.append(f"| {name} | {fmt(block['mean'])} | {ci(block)} | "
                     f"{fmt(tm['humaneval'])} | {fmt(tm['gsm8k'])} | {fmt(tm['truthfulqa'])} |")
    lines.append("")
    lines.append("## Paired composite difference (H − X)")
    lines.append("")
    lines.append(f"- Point difference: **{fmt(pc_paired['mean_difference'])}**")
    lines.append(f"- 95% paired percentile CI: **[{fmt(pc_paired['ci_low'])}, "
                 f"{fmt(pc_paired['ci_high'])}]**")
    lines.append(f"- Interval contains zero: "
                 f"**{'yes' if pc_paired['ci_low'] <= 0 <= pc_paired['ci_high'] else 'no'}**")
    lines.append("")
    lines.append("## Cross-check against the stored summaries")
    lines.append("")
    lines.append("The recomputed per-task means are compared with the values stored in each "
                 "arm's `results/t2/<arm>/eval.json` summary. A mismatch would mean this "
                 "reader is not reporting the registered statistic.")
    lines.append("")
    lines.append("| arm | task | recomputed | stored | agreement |")
    lines.append("| --- | --- | ---: | ---: | --- |")
    ok = True
    for name, arm in [(PAIR[0], left), (PAIR[1], right)]:
        for task in TASKS:
            recomputed = arm.task_means[task]
            stored_value = (stored[name]["stored_per_task"] or {}).get(
                {"humaneval": "humaneval_pass_at_1", "gsm8k": "gsm8k_exact_match",
                 "truthfulqa": "truthfulqa_mc1"}[task])
            agree = (stored_value is not None
                     and abs(recomputed - stored_value) < 1e-12)
            ok = ok and agree
            lines.append(f"| {name} | {task} | {fmt(recomputed)} | {fmt(stored_value)} | "
                         f"{'yes' if agree else 'NO'} |")
    lines.append("")
    lines.append(f"All recomputed task means match the stored summaries: "
                 f"**{'yes' if ok else 'NO'}**.")
    lines.append("")
    lines.append("## What this does not establish")
    lines.append("")
    lines.append("- It is not the registered verdict: that needs the five arms including `H*`, "
                 "the registered thresholds, and the kill conditions applied in order.")
    lines.append("- It does not correct the legacy dispatch. A corrected-dispatch sensitivity "
                 "run from the same checkpoints is registered and not launched.")
    lines.append("- It makes no claim about SELVEDGE vs any external system, and no GPU or "
                 "competitive performance claim.")
    lines.append("")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))

    # A machine-readable companion so downstream tools never parse the markdown.
    payload = {
        "schema": "selvedge/t2-partial/v1",
        "created_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "exploratory": True,
        "not_the_registered_verdict": True,
        "pair": [PAIR[0], PAIR[1]],
        "difference_direction": "H - X",
        "seed": SEED,
        "resamples": RESAMPLES,
        "per_task": table,
        "composite": {"X": pc_x, "H": pc_h, "paired_H_minus_X": pc_paired},
        "context_arms": {name: composite_bootstrap(arm.task_values, SEED, RESAMPLES)
                         for name, arm in context.items()},
        "inputs": stored,
        "recomputed_matches_stored": ok,
    }
    json_path = os.path.splitext(args.out)[0] + ".json"
    with open(json_path, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, sort_keys=True)
        handle.write("\n")
    print(f"wrote {args.out} and {json_path}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
